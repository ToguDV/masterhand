/**
 * models.dev embeds logos inline by stripping the fixed size and forcing every
 * painted fill/stroke to `currentColor`, so one asset works on both themes;
 * the served `/logos/{id}.svg` files still carry their original paint. Mirror
 * that normalization and minify (the artwork is paths-only, no text nodes).
 */
function normalize(svg) {
  return svg
    .replace(/<svg\b([^>]*)>/i, (_, attributes) => `<svg${attributes.replace(/\s(width|height)="[^"]*"/gi, "")}>`)
    .replace(/\sfill="(?!none|currentColor)[^"]*"/gi, ' fill="currentColor"')
    .replace(/\sstroke="(?!none|currentColor)[^"]*"/gi, ' stroke="currentColor"')
    .replace(/>\s+</g, "><")
    .trim()
}

async function fetchLogo(id) {
  const response = await fetch(`${LOGOS_URL}/${id}.svg`)
  if (!response.ok) throw new Error(`${id}: HTTP ${response.status}`)
  const svg = await response.text()
  if (!svg.includes("<svg") || !svg.includes("</svg>")) throw new Error(`${id}: not an SVG`)
  return svg
}

function constName(id) {
  return id.replace(/[^a-zA-Z0-9]+(.)/g, (_, char) => char.toUpperCase()).replace(/[^a-zA-Z0-9]/g, "")
}

async function main() {
  const fallback = await fetchLogo("__masterhand-missing-provider__")
  const blocks = []
  const entries = []
  for (const [id, ...aliases] of PROVIDERS) {
    const raw = await fetchLogo(id)
    if (raw === fallback) throw new Error(`${id}: models.dev serves the generic fallback logo`)
    for (const alias of aliases) {
      if ((await fetchLogo(alias)) !== raw) throw new Error(`${alias}: logo differs from ${id}, vendor it separately`)
    }
    const name = constName(id)
    blocks.push(`const ${name} = ${JSON.stringify(normalize(raw))}`)
    entries.push(`  ${constName(id) === id ? id : `"${id}"`}: ${name},`)
    for (const alias of aliases) entries.push(`  "${alias}": ${name},`)
    console.log(`${id} (${aliases.length + 1} key${aliases.length === 0 ? "" : "s"})`)
  }

  const file = `// Generated by scripts/generate-provider-icons.mjs — do not edit by hand.
//
// Original provider logos from models.dev (MIT): https://github.com/anomalyco/models.dev
// Each mark keeps the provider's original geometry; paints are normalized to
// currentColor so one asset works on light and dark themes. Logos are the
// providers' trademarks and identify their integration only.

${blocks.join("\n\n")}

/** Brand SVG markup by integration id (aliases share one artwork). */
export const providerIconSvgs: Readonly<Record<string, string>> = {
${entries.join("\n")}
}
`
  await writeFile(OUT_FILE, file)
  console.log(`\nWrote ${entries.length} entries to ${path.relative(process.cwd(), OUT_FILE)}`)
}

main().catch((error) => {
  console.error(error)
  process.exit(1)
})
