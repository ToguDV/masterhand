#!/usr/bin/env node
/**
 * Regenerates `src/provider-icons.generated.ts` from models.dev.
 *
 * opencode's integration catalog exposes no logos, so the original brand marks
 * are vendored from models.dev (MIT, https://github.com/anomalyco/models.dev) —
 * the same catalog opencode itself is built from. Logos are trademarks of their
 * owners and are used here only to identify the provider.
 *
 * Usage: npm run icons:providers -w @masterhand/client-core
 */
import { writeFile } from "node:fs/promises"
import path from "node:path"
import { fileURLToPath } from "node:url"

const LOGOS_URL = "https://models.dev/logos"
const OUT_FILE = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "src", "provider-icons.generated.ts")

/**
 * Vendored providers: the first id is the icon's own; any extra id shares the
 * same artwork (checked byte-for-byte below), e.g. regional or plan variants.
 * Keep this list curated to popular integrations — the rest falls back to the
 * monogram.
 */
