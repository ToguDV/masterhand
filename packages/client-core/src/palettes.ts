/**
 * Selectable color themes.
 *
 * One shared definition for both clients so web (`data-palette` CSS blocks)
 * and mobile (`paletteFor`) can never drift: each theme carries a complete
 * per-mode token set (canvas/surface/text/hairlines plus the accent family,
 * code surfaces and syntax hues). Light/dark stays an independent axis: the
 * mode picks the column, the theme picks the row.
 *
 * `paper` is the default ink-on-paper theme (the values the design system
 * shipped with). Unknown or missing stored values fall back to it, including
 * the legacy accent-color ids (`emerald`, `violet`, …) from the previous
 * accent-only picker.
 */

